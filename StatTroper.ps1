# Maximize the PowerShell window to fullscreen

$psWindow = (New-Object -ComObject Shell.Application).Windows() | Where-Object { $_.HWND -eq (Get-Process -Id $PID).MainWindowHandle }

$psWindow.Maximize()



# Get console width and calculate positions

$consoleWidth = [Console]::WindowWidth

$startY = 2

$leftX = 2

$rightX = [Math]::Floor($consoleWidth / 2) + 2



# Split banners into lines

$bannerLeftLines = $bannerLeft -split "`n"

$bannerRightLines = $bannerRight -split "`n"

$maxLines = [Math]::Max($bannerLeftLines.Length, $bannerRightLines.Length)



# Animation loop

while ($true) {

    # Clear the console

    Clear-Host



    # Display banners

    for ($i = 0; $i -lt $maxLines; $i++) {

        # Set cursor for left banner

        if ($i -lt $bannerLeftLines.Length) {

            [Console]::SetCursorPosition($leftX, $startY + $i)

            Write-Host $bannerLeftLines[$i] -NoNewline -ForegroundColor Cyan

        }

        # Set cursor for right banner

        if ($i -lt $bannerRightLines.Length) {

            [Console]::SetCursorPosition($rightX, $startY + $i)

            Write-Host $bannerRightLines[$i] -NoNewline -ForegroundColor Magenta

        }

    }



    # Add a simple animation effect (e.g., color toggle)

    Start-Sleep -Milliseconds 500



    # Swap colors for animation effect

    $tempColor = $bannerLeftLines

    $bannerLeftLines = $bannerRightLines

    $bannerRightLines = $tempColor

}
